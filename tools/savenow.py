#!/usr/bin/env python3
"""The field maps with a save point (M7a, docs/specs/save-now.md): those whose
script has op 138 (SAVEPOINT), as runtime/save_point_maps.h lists them; and
the maps a warp reaches (M7b), as runtime/warp_maps.h does.

    python tools/savenow.py check               # the headers against your disc
    python tools/savenow.py generate --write    # rewrite them from it

A Continue sets sys[15] to 20000, which a map's script takes as "back from my
save point"; only the first list's maps have one. Save now uses it to choose
the fallback a save made off a save point carries for the game alone. A warp
needs a map's script and its geometry both; the 5xx are ship-battle stages,
which start through op 210, not a warp.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

HEADER = ROOT / "runtime" / "save_point_maps.h"
WARP_HEADER = ROOT / "runtime" / "warp_maps.h"  # M7b
_ENTRY = re.compile(r"0x([0-9A-F]{8})u, /\* a(\d{3}[a-z]) \*/")


def scan_all(data: Path) -> tuple[list[str], list[str]]:
    """(the maps whose script has op 138, the maps a warp can reach: a script
    and its geometry both, below 500), each like '116a', in order."""
    import sct
    from soa import aklz, disc

    saves, warps = [], []
    with disc.open_data(data) as src:
        paths = sorted(src.paths())
        lower = {q.lower() for q in paths}
        for q in paths:
            m = re.fullmatch(r"field/me(\d{3}[a-z])\.sct", q.lower())
            if not m:
                continue
            name = m.group(1)
            if f"field/a{name}.mld" in lower and int(name[:3]) < 500:
                warps.append(name)
            d = aklz.decompress(src.read_path(q))
            if any("[138]" in line for _, _, _, lines in sct.script(d) for line in lines):
                saves.append(name)
    return sorted(saves), sorted(warps)  # by map, whatever the disc's spelling (ME199F sorts first)


def scan(data: Path) -> list[str]:
    """Every field map (like '116a') whose script has op 138, in order."""
    return scan_all(data)[0]


def word(name: str) -> int:
    """The map as api->map() gives it: number << 8 | letter."""
    return int(name[:3]) << 8 | ord(name[3])


def _header(maps: list[str], guard: str, count: str, array: str, what: str) -> str:
    rows = "".join(f"    0x{word(m):08X}u, /* a{m} */\n" for m in maps)
    return (
        f"/* Generated by tools/savenow.py from the disc: {what},\n"
        " * as number << 8 | letter. Map names and facts about their files, no game\n"
        " * data. Do not edit: run `python tools/savenow.py generate --write`. */\n"
        f"#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n\n"
        f"#define {count} {len(maps)}\n"
        f"static const uint32_t {array}[{count}] = {{\n{rows}}};\n\n#endif\n"
    )


def header(maps: list[str]) -> str:
    return _header(
        maps,
        "SOA_SAVE_POINT_MAPS_H",
        "SAVE_POINT_MAPS",
        "k_save_point_maps",
        "the field maps whose script has op 138\n * (SAVEPOINT; M7a, docs/specs/save-now.md)",
    )


def warp_header(maps: list[str]) -> str:
    return _header(
        maps,
        "SOA_WARP_MAPS_H",
        "WARP_MAPS",
        "k_warp_maps",
        "the maps a warp reaches, a script and its\n * geometry both, below 500 (M7b, docs/specs/debug-actions.md)",
    )


def listed(text: str) -> list[str]:
    return [m.group(2) for m in _ENTRY.finditer(text)]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=("check", "generate"))
    ap.add_argument("--data", type=Path, default=ROOT / "extracted")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    saves, warps = scan_all(args.data)
    made = ((HEADER, header(saves), saves), (WARP_HEADER, warp_header(warps), warps))
    if args.command == "generate":
        for path, text, maps in made:
            if args.write:
                path.write_bytes(text.encode("utf-8"))
                print(f"wrote {path.relative_to(ROOT)}: {len(maps)} maps")
            else:
                print(text, end="")
        return 0
    bad = 0
    for path, _, maps in made:
        have = listed(path.read_text(encoding="utf-8")) if path.exists() else []
        if have != maps:
            missing = sorted(set(maps) - set(have))
            extra = sorted(set(have) - set(maps))
            print(f"{path.name} disagrees with the disc: missing {missing}, extra {extra}")
            bad = 1
        else:
            print(f"{path.name}: {len(maps)} maps, as the disc has them")
    return bad


if __name__ == "__main__":
    sys.exit(main())
