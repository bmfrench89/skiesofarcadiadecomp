#!/usr/bin/env python3
"""The field maps with a save point (M7a, docs/specs/save-now.md): those whose
script has op 138 (SAVEPOINT), as runtime/save_point_maps.h lists them.

    python tools/savenow.py check               # the header against your disc
    python tools/savenow.py generate --write    # rewrite the header from it

A Continue sets sys[15] to 20000, which a map's script takes as "back from my
save point"; only these maps have one. Save now uses the list to choose the
fallback a save made off a save point carries for the game alone.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

HEADER = ROOT / "runtime" / "save_point_maps.h"
_ENTRY = re.compile(r"0x([0-9A-F]{8})u, /\* a(\d{3}[a-z]) \*/")


def scan(data: Path) -> list[str]:
    """Every field map (like '116a') whose script has op 138, in order."""
    import sct
    from soa import aklz, disc

    out = []
    with disc.open_data(data) as src:
        for q in sorted(src.paths()):
            m = re.fullmatch(r"field/me(\d{3}[a-z])\.sct", q.lower())
            if not m:
                continue
            d = aklz.decompress(src.read_path(q))
            if any("[138]" in line for _, _, _, lines in sct.script(d) for line in lines):
                out.append(m.group(1))
    return out


def word(name: str) -> int:
    """The map as api->map() gives it: number << 8 | letter."""
    return int(name[:3]) << 8 | ord(name[3])


def header(maps: list[str]) -> str:
    rows = "".join(f"    0x{word(m):08X}u, /* a{m} */\n" for m in maps)
    return (
        "/* Generated by tools/savenow.py from the disc: the field maps whose script has op\n"
        " * 138 (SAVEPOINT), as number << 8 | letter (M7a, docs/specs/save-now.md). A map\n"
        " * name and a fact about its script, no game data. Do not edit: run\n"
        " * `python tools/savenow.py generate --write`. */\n"
        "#ifndef SOA_SAVE_POINT_MAPS_H\n#define SOA_SAVE_POINT_MAPS_H\n\n#include <stdint.h>\n\n"
        f"#define SAVE_POINT_MAPS {len(maps)}\n"
        f"static const uint32_t k_save_point_maps[SAVE_POINT_MAPS] = {{\n{rows}}};\n\n#endif\n"
    )


def listed(text: str) -> list[str]:
    return [m.group(2) for m in _ENTRY.finditer(text)]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=("check", "generate"))
    ap.add_argument("--data", type=Path, default=ROOT / "extracted")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    maps = scan(args.data)
    if args.command == "generate":
        text = header(maps)
        if args.write:
            HEADER.write_bytes(text.encode("utf-8"))
            print(f"wrote {HEADER.relative_to(ROOT)}: {len(maps)} maps")
        else:
            print(text, end="")
        return 0
    have = listed(HEADER.read_text(encoding="utf-8"))
    if have != maps:
        missing = sorted(set(maps) - set(have))
        extra = sorted(set(have) - set(maps))
        print(f"save_point_maps.h disagrees with the disc: missing {missing}, extra {extra}")
        return 1
    print(f"save_point_maps.h: {len(maps)} maps, as the disc's scripts have them")
    return 0


if __name__ == "__main__":
    sys.exit(main())
